// cry_to_rgb converts a CRY pixel to 0x00RRGGBB.
@[direct_array_access; inline]
pub fn cry_to_rgb(pixel u32) u32 {
	chroma := (pixel >> 8) & 0xff
	luma := pixel & 0xff
	r := u32(cry_red[chroma]) * luma / 255
	g := u32(cry_green[chroma]) * luma / 255
	b := u32(cry_blue[chroma]) * luma / 255
	return (r << 16) | (g << 8) | b
}

// rgb16_to_rgb converts a Jaguar RGB16 pixel (red 15..11, blue 10..6,
// green 5..0) to 0x00RRGGBB.
@[inline]
pub fn rgb16_to_rgb(pixel u32) u32 {
	r5 := (pixel >> 11) & 0x1f
	b5 := (pixel >> 6) & 0x1f
	g6 := pixel & 0x3f
	r := (r5 << 3) | (r5 >> 2)
	g := (g6 << 2) | (g6 >> 4)
	b := (b5 << 3) | (b5 >> 2)
	return (r << 16) | (g << 8) | b
}
