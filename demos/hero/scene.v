module main

import jagkit { at, idx, imm, inc, ind, lbl }

// What each state draws between the stage and the text.

const combo_x = 8
const combo_y = 92 // rows from the top
const digit_step = 18
const badge_x = 10
const badge_y = 140
const combo_shown = 4 // a combo is drawn from this many notes on

// point loads the address of a label plus an offset.
fn (mut g Game) point(name string, offset int, reg jagkit.Ea) {
	g.m.lea(lbl(name), reg)
	if offset != 0 {
		g.m.add(.l, imm(offset), reg)
	}
}

fn (mut g Game) scenes() {
	mut m := g.m

	// The title: the logo, breathing with the beat.
	m.label('draw_title')
	m.moveq(0, d7)
	m.move(.w, lbl('beat_phase'), d7)
	m.lsl(.w, imm(3), d7)
	for line in 0 .. 2 {
		g.point('logo_place', line * 16 * 8, a3)
		m.add(.l, d7, a3)
		g.point('tpl_logo', line * template_bytes, a0)
		g.placed()
	}
	m.rts()

	// Song select: a gem points at the chosen song.
	m.label('draw_select')
	m.moveq(0, d0)
	m.move(.w, lbl('chosen'), d0)
	m.mulu(imm(3 * template_bytes), d0)
	m.lea(lbl('tpl_gems'), a0)
	m.add(.l, d0, a0)
	m.moveq(0, d1)
	m.move(.w, lbl('chosen'), d1)
	m.mulu(imm(4 * 8 * 2), d1)
	m.add(.w, imm(list_top * 8 * 2 - 2), d1)
	m.moveq(6, d0)
	m.move(.w, imm(0x1010), d2)
	m.bsr('emit')
	m.rts()

	// The results: the rank, landing.
	m.label('draw_results')
	m.moveq(0, d0)
	m.move(.w, lbl('rank'), d0)
	m.mulu(imm(template_bytes), d0)
	m.lea(lbl('tpl_ranks'), a0)
	m.add(.l, d0, a0)
	m.moveq(0, d4)
	m.move(.w, lbl('results_timer'), d4)
	m.lsl(.w, imm(3), d4)
	m.lea(lbl('rank_place'), a3)
	m.add(.l, d4, a3)
	g.placed()
	m.rts()

	// Playing: beat lines, notes, bursts, the judgement, the combo, the
	// multiplier and the health meter.
	m.label('draw_play')
	m.bsr('draw_lines')
	m.bsr('draw_notes')
	m.bsr('draw_bursts')
	m.bsr('draw_judge')
	m.bsr('draw_combo')
	m.lea(lbl('tpl_frame'), a0)
	m.move(.w, imm(meter_x - 4), d0)
	m.move(.w, imm((meter_top - 2) * 2), d1)
	m.moveq(0, d2)
	m.bsr('emit')
	m.moveq(0, d4)
	m.move(.w, lbl('health'), d4)
	m.b(.eq, 'no_meter')
	m.lea(lbl('tpl_meter'), a0)
	m.move(.w, imm(meter_x), d0)
	m.move(.w, imm((meter_top + meter_height) * 2), d1)
	m.sub(.w, d4, d1)
	m.sub(.w, d4, d1)
	m.bsr('emit_meter')
	m.label('no_meter')
	m.rts()

	g.draw_lines()
	g.draw_notes()
	g.draw_hits()
}

// draw_lines draws a line across the highway for every beat in view, a
// brighter one on the first beat of a bar.
fn (mut g Game) draw_lines() {
	mut m := g.m
	m.label('draw_lines')
	m.move(.w, lbl('clock'), d7)
	m.add(.w, imm(1), d7) // the list is shown next frame
	m.move(.w, d7, d6)
	m.sub(.w, imm(back_frames), d6)
	m.label('lines_advance')
	m.move(.w, lbl('next_line'), d0)
	m.cmp(.w, d6, d0)
	m.b(.ge, 'lines_ready')
	m.add(.w, lbl('beat_frames'), d0)
	m.move(.w, d0, lbl('next_line'))
	m.add(.w, imm(1), lbl('line_index'))
	m.bra('lines_advance')
	m.label('lines_ready')
	m.move(.w, lbl('next_line'), d5)
	m.move(.w, lbl('line_index'), d4)
	m.move(.l, lbl('view_ptr'), a4)
	m.label('lines_next')
	m.move(.w, d5, d0)
	m.sub(.w, d7, d0)
	m.cmp(.w, lbl('look'), d0)
	m.b(.gt, 'lines_done')
	m.add(.w, imm(back_frames), d0)
	m.and(.l, imm(0xffff), d0)
	m.lsl(.l, imm(5), d0)
	m.lea(idx(0, a4, d0), a3)
	m.lea(lbl('tpl_line'), a0)
	m.move(.w, d4, d0)
	m.and(.w, imm(3), d0)
	m.b(.ne, 'beat_only')
	m.lea(lbl('tpl_bar'), a0)
	m.label('beat_only')
	m.move(.w, at(6, a3), d0)
	m.move(.w, at(2, a3), d1)
	m.move(.w, at(20, a3), d2)
	m.bsr('emit')
	m.add(.w, lbl('beat_frames'), d5)
	m.add(.w, imm(1), d4)
	m.bra('lines_next')
	m.label('lines_done')
	m.rts()
}

// draw_notes draws the notes in view, the furthest first so nearer ones
// cover them. Struck notes are gone; missed ones are grey.
fn (mut g Game) draw_notes() {
	mut m := g.m
	m.label('draw_notes')
	m.move(.w, lbl('clock'), d7)
	m.add(.w, imm(1), d7)
	m.move(.l, lbl('chart_ptr'), a3)
	m.moveq(0, d6)
	m.move(.w, lbl('draw_first'), d6)
	m.move(.w, d7, d2)
	m.sub(.w, imm(back_frames), d2)
	m.label('notes_advance')
	m.move(.l, d6, d0)
	m.lsl(.l, imm(2), d0)
	m.cmp(.w, idx(0, a3, d0), d2)
	m.b(.le, 'notes_first')
	m.add(.l, imm(1), d6)
	m.bra('notes_advance')
	m.label('notes_first')
	m.move(.w, d6, lbl('draw_first'))
	// Find the furthest note in view.
	m.move(.l, d6, d5)
	m.label('notes_reach')
	m.move(.l, d5, d0)
	m.lsl(.l, imm(2), d0)
	m.move(.w, idx(0, a3, d0), d1)
	m.sub(.w, d7, d1)
	m.cmp(.w, lbl('look'), d1)
	m.b(.gt, 'notes_reached')
	m.add(.l, imm(1), d5)
	m.move(.l, d5, d0)
	m.sub(.l, d6, d0)
	m.cmp(.w, imm(max_drawn_notes), d0)
	m.b(.cs, 'notes_reach')
	m.label('notes_reached')
	m.sub(.l, imm(1), d5)
	m.lea(jagkit.abs(note_state), a5)
	m.move(.l, lbl('view_ptr'), a6)
	m.label('notes_next')
	m.cmp(.l, d6, d5)
	m.b(.lt, 'notes_done')
	m.move(.b, idx(0, a5, d5), d4)
	m.cmp(.b, imm(1), d4)
	m.b(.eq, 'note_skip')
	m.move(.l, d5, d0)
	m.lsl(.l, imm(2), d0)
	m.moveq(0, d3)
	m.move(.b, idx(2, a3, d0), d3) // the lane
	m.move(.w, idx(0, a3, d0), d0)
	m.sub(.w, d7, d0)
	m.add(.w, imm(back_frames), d0)
	m.and(.l, imm(0xffff), d0)
	m.lsl(.l, imm(5), d0)
	m.lea(idx(0, a6, d0), a4)
	m.move(.w, ind(a4), d1)
	m.b(.mi, 'note_skip')
	m.add(.w, d3, d3)
	m.move(.w, idx(8, a4, d3), d0)
	m.move(.w, at(4, a4), d2)
	m.lea(lbl('tpl_grey'), a0)
	m.cmp(.b, imm(2), d4)
	m.b(.eq, 'note_template')
	m.mulu(imm(3 * template_bytes / 2), d3)
	m.lea(lbl('tpl_gems'), a0)
	m.add(.l, d3, a0)
	m.add(.w, at(18, a4), a0)
	m.label('note_template')
	m.bsr('emit')
	m.label('note_skip')
	m.sub(.l, imm(1), d5)
	m.bra('notes_next')
	m.label('notes_done')
	m.rts()
}

// draw_hits draws what a hit leaves: bursts on the targets, the judgement,
// the combo and the multiplier.
fn (mut g Game) draw_hits() {
	mut m := g.m
	m.label('draw_bursts')
	for lane in 0 .. lanes {
		skip := m.unique('no_burst')
		big := m.unique('burst_big')
		m.moveq(0, d4)
		m.move(.w, lbl('burst_time_${lane}'), d4)
		m.cmp(.w, imm(burst_frames_shown), d4)
		m.b(.cc, skip)
		m.lsr(.w, imm(1), d4)
		m.mulu(imm(template_bytes), d4)
		g.point('tpl_bursts', lane * burst_frames * template_bytes, a0)
		m.add(.l, d4, a0)
		g.point('burst_place', lane * 8, a3)
		m.tst(.w, lbl('burst_kind_${lane}'))
		m.b(.eq, big)
		m.add(.l, imm(lanes * 8), a3)
		m.label(big)
		g.placed()
		m.label(skip)
	}
	m.rts()

	m.label('draw_judge')
	m.moveq(0, d4)
	m.move(.w, lbl('judge_time'), d4)
	m.cmp(.w, imm(judge_frames_shown), d4)
	m.b(.cc, 'judge_hidden')
	m.moveq(0, d5)
	m.move(.w, lbl('judge_kind'), d5)
	m.move(.l, d5, d0)
	m.mulu(imm(template_bytes), d0)
	m.lea(lbl('tpl_judge'), a0)
	m.add(.l, d0, a0)
	m.mulu(imm(judge_frames_shown), d5)
	m.add(.l, d4, d5)
	m.lsl(.l, imm(3), d5)
	m.lea(lbl('pop_table'), a3)
	m.add(.l, d5, a3)
	g.placed()
	m.label('judge_hidden')
	m.rts()

	m.label('draw_combo')
	m.lea(lbl('tpl_digits'), a5)
	m.cmp(.w, imm(multiplier_tiers - 1), lbl('tier'))
	m.b(.ne, 'digits_gold')
	m.add(.l, imm(digit_glyphs.len * template_bytes), a5)
	m.label('digits_gold')
	m.moveq(0, d5)
	m.move(.w, lbl('combo'), d5)
	m.cmp(.w, imm(combo_shown), d5)
	m.b(.cs, 'combo_hidden')
	m.lea(lbl('combo_digits_end'), a4)
	m.moveq(0, d6)
	m.label('combo_divide')
	m.divu(imm(10), d5)
	m.swap(d5)
	m.move(.w, d5, jagkit.dec(a4))
	m.move(.w, imm(0), d5)
	m.swap(d5)
	m.add(.w, imm(1), d6)
	m.tst(.l, d5)
	m.b(.ne, 'combo_divide')
	m.move(.w, imm(combo_x), d7)
	m.label('combo_digit')
	m.moveq(0, d0)
	m.move(.w, inc(a4), d0)
	m.mulu(imm(template_bytes), d0)
	m.move(.l, a5, a0)
	m.add(.l, d0, a0)
	m.move(.w, d7, d0)
	m.move(.w, imm(combo_y * 2), d1)
	m.move(.w, imm(unit_scale), d2)
	m.bsr('emit')
	m.add(.w, imm(digit_step), d7)
	m.sub(.w, imm(1), d6)
	m.b(.ne, 'combo_digit')
	m.label('combo_hidden')
	// The multiplier: X and its factor.
	m.moveq(0, d5)
	m.move(.w, lbl('tier'), d5)
	m.b(.eq, 'badge_hidden')
	m.add(.w, d5, d5)
	m.lea(lbl('tier_factors'), a3)
	m.move(.w, idx(0, a3, d5), d5)
	m.move(.l, a5, a0)
	m.add(.l, imm((digit_glyphs.len - 1) * template_bytes), a0)
	m.move(.w, imm(badge_x), d0)
	m.move(.w, imm(badge_y * 2), d1)
	m.move(.w, imm(unit_scale), d2)
	m.bsr('emit')
	m.mulu(imm(template_bytes), d5)
	m.move(.l, a5, a0)
	m.add(.l, d5, a0)
	m.move(.w, imm(badge_x + digit_step), d0)
	m.move(.w, imm(badge_y * 2), d1)
	m.move(.w, imm(unit_scale), d2)
	m.bsr('emit')
	m.label('badge_hidden')
	m.rts()
}
