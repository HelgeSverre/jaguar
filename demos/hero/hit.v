module main

import jagkit { at, idx, imm, ind, lbl }

// hit scores a press: a0 is the note's chart entry, a1 its state, d1 the
// frames until it was due (below zero: late) and d6 its lane.
fn (mut g Game) hit() {
	mut m := g.m
	m.label('hit')
	m.move(.b, imm(1), ind(a1))
	m.move(.w, d1, d2)
	m.b(.pl, 'hit_distance')
	m.neg(.w, d2)
	m.label('hit_distance')
	m.moveq(judge_perfect, d3)
	m.cmp(.w, imm(window_perfect), d2)
	m.b(.le, 'hit_judged')
	m.moveq(judge_great, d3)
	m.cmp(.w, imm(window_great), d2)
	m.b(.le, 'hit_judged')
	m.moveq(judge_good, d3)
	m.label('hit_judged')
	m.move(.w, d3, lbl('judge_kind'))
	m.move(.w, imm(0), lbl('judge_time'))
	m.moveq(0, d4)
	m.move(.w, d3, d4)
	m.add(.w, d4, d4)
	m.lea(lbl('perfects'), a2)
	m.add(.w, imm(1), idx(0, a2, d4))

	// Combo, and the multiplier it earns.
	m.add(.w, imm(1), lbl('combo'))
	m.move(.w, lbl('combo'), d5)
	m.cmp(.w, lbl('max_combo'), d5)
	m.b(.ls, 'combo_counted')
	m.move(.w, d5, lbl('max_combo'))
	m.label('combo_counted')
	m.moveq(0, d0)
	for tier, need in tier_combos {
		m.cmp(.w, imm(need), d5)
		m.b(.cs, 'tier_known')
		m.moveq(tier + 1, d0)
	}
	m.label('tier_known')
	m.cmp(.w, lbl('tier'), d0)
	m.b(.eq, 'tier_kept')
	m.move(.w, d0, lbl('tier'))
	m.cmp(.w, imm(multiplier_tiers - 1), d0)
	m.b(.ne, 'tier_kept')
	m.push([d1, d3, d4, d6, a0])
	m.moveq(event_overdrive, d0)
	m.bsr('show_event')
	m.pop([d1, d3, d4, d6, a0])
	m.label('tier_kept')

	// Points: the judgement's worth times the multiplier.
	m.lea(lbl('judge_points'), a2)
	m.move(.w, idx(0, a2, d4), d5)
	m.moveq(0, d0)
	m.move(.w, lbl('tier'), d0)
	m.add(.w, d0, d0)
	m.lea(lbl('tier_factors'), a2)
	m.mulu(idx(0, a2, d0), d5)
	m.add(.l, d5, lbl('score'))
	m.lea(lbl('judge_health'), a2)
	m.move(.w, idx(0, a2, d4), d5)
	m.add(.w, d5, lbl('health'))
	m.cmp(.w, imm(health_full), lbl('health'))
	m.b(.le, 'health_kept')
	m.move(.w, imm(health_full), lbl('health'))
	m.label('health_kept')

	// The lane lights up and bursts.
	m.moveq(0, d4)
	m.move(.w, d6, d4)
	m.add(.w, d4, d4)
	g.lane_word('lane_glow')
	m.move(.w, imm(glow_levels - 1), ind(a2))
	g.lane_word('target_flash')
	m.move(.w, imm(8), ind(a2))
	g.lane_word('target_kind')
	m.move(.w, imm(2), ind(a2))
	g.lane_word('burst_time')
	m.move(.w, imm(0), ind(a2))
	g.lane_word('burst_kind')
	m.move(.w, imm(0), ind(a2))
	m.tst(.w, d3)
	m.b(.eq, 'burst_big')
	m.move(.w, imm(1), ind(a2))
	m.label('burst_big')

	// A late hit brings back a lead guitar that was silent when its note
	// came round.
	m.move(.w, imm(1), lbl('hero_live'))
	m.tst(.w, d1)
	m.b(.gt, 'hit_done')
	m.moveq(0, d0)
	m.move(.b, at(3, a0), d0)
	m.bclr(7, d0)
	m.b(.ne, 'hit_harmony')
	m.tst(.w, lbl('hero_quiet'))
	m.b(.eq, 'hit_done')
	m.move(.w, imm(0), lbl('hero_quiet'))
	g.revive(voice_hero, rec_hero_level)
	m.bra('hit_done')
	m.label('hit_harmony')
	m.tst(.w, lbl('harmony_quiet'))
	m.b(.eq, 'hit_done')
	m.move(.w, imm(0), lbl('harmony_quiet'))
	g.revive(voice_harmony, rec_harmony_level)
	m.label('hit_done')
	// Every fifty notes from a hundred on, a banner.
	m.moveq(0, d0)
	m.move(.w, lbl('combo'), d0)
	m.divu(imm(streak_step), d0)
	m.move(.l, d0, d1)
	m.swap(d1)
	m.tst(.w, d1)
	m.b(.ne, 'no_streak')
	m.cmp(.w, imm(2), d0)
	m.b(.cs, 'no_streak')
	m.cmp(.w, imm(streak_banners + 1), d0)
	m.b(.ls, 'streak_known')
	m.moveq(streak_banners + 1, d0)
	m.label('streak_known')
	m.add(.w, imm(event_streak - 2), d0)
	m.bra('show_event')
	m.label('no_streak')
	m.rts()
}

// revive sounds MIDI note d0 on a lead guitar at its full level.
fn (mut g Game) revive(v int, level_field int) {
	mut m := g.m
	m.bsr('note_step')
	m.move(.l, d0, g.voice(v, v_step))
	m.move(.l, lbl('song_rec'), a5)
	m.move(.l, at(level_field, a5), g.voice(v, v_level))
	m.move(.l, at(rec_hero_sustain, a5), g.voice(v, v_rate))
	g.trigger(v)
}

// miss breaks the combo, silences the lead guitars and costs health; a0 is
// the note's chart entry. stray is a press with no note near it.
fn (mut g Game) miss() {
	mut m := g.m
	m.label('miss')
	m.add(.w, imm(1), lbl('misses'))
	m.move(.w, imm(judge_miss), lbl('judge_kind'))
	m.move(.w, imm(0), lbl('judge_time'))
	m.moveq(0, d4)
	m.move(.b, at(2, a0), d4)
	m.add(.w, d4, d4)
	g.lane_word('target_flash')
	m.move(.w, imm(8), ind(a2))
	g.lane_word('target_kind')
	m.move(.w, imm(3), ind(a2))
	m.tst(.w, lbl('hero_live'))
	m.b(.eq, 'already_quiet')
	m.move(.w, imm(0), lbl('hero_live'))
	m.move(.l, imm(cut_rate), g.voice(voice_hero, v_rate))
	m.move(.l, imm(cut_rate), g.voice(voice_harmony, v_rate))
	g.sfx(150, 55, 5000, 160)
	m.label('already_quiet')
	m.move(.w, imm(health_miss), d0)
	m.bra('lose')

	m.label('stray')
	m.add(.w, imm(1), lbl('strays'))
	m.moveq(0, d4)
	m.move(.w, d6, d4)
	m.add(.w, d4, d4)
	g.lane_word('target_flash')
	m.move(.w, imm(4), ind(a2))
	g.lane_word('target_kind')
	m.move(.w, imm(3), ind(a2))
	g.sfx(320, 180, 2200, 40)
	m.move(.w, imm(health_stray), d0)

	// lose takes d0 health and the combo; at nothing left the song fails.
	m.label('lose')
	m.move(.w, imm(0), lbl('combo'))
	m.move(.w, imm(0), lbl('tier'))
	m.sub(.w, d0, lbl('health'))
	m.b(.gt, 'still_alive')
	m.move(.w, imm(0), lbl('health'))
	m.tst(.w, lbl('failed'))
	m.b(.ne, 'still_alive')
	m.move(.w, imm(1), lbl('failed'))
	m.move(.w, imm(seq_off), lbl('seq_mode'))
	g.mute(cut_rate)
	g.sfx(400, 30, 9000, 900)
	m.move(.w, imm(finish_frames), lbl('finish_timer'))
	m.push([d0, a0])
	g.say(event_column, event_row, 2, '    SONG FAILED     ')
	m.pop([d0, a0])
	m.move(.w, imm(0), lbl('event_timer'))
	m.label('still_alive')
	m.rts()
}
