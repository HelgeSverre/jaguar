// The maps of GHOSTGRID: twelve rooms of 28 by 20 tiles, written as text.
//
//   #  wall               c  cover block (hides a crouching figure)
//   .  floor              X  the exit pad
//   @  where the figure starts (the first room of a mission)
//   [  where it arrives from the previous room   ]  from the next room
//   D  a door to the next room                   U  a door back
//   $  a data chip         1-9  waypoints of the guards' routes
//   A B C  a camera on a pillar (the first, second and third of the room)
//
// A mission is these maps plus a row of the table in missions.v: which rooms,
// which guards walk which waypoints, which cameras sweep where. Rooms are
// padded with wall below their last row. `,`, `;` and the other lit tiles
// are never in the text: they are what a cone turns the floor into.
