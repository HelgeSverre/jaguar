// font_first is the character code of the font's first glyph.
pub const font_first = 32
const font_count = 64

// font_8x8 is the font as 8x8 cells, one byte a row, for ASCII 32..95:
// capitals, digits and punctuation. The glyph of character c starts at
// (c - font_first) * 8.
pub fn font_8x8() []u8 {
	mut font := []u8{len: font_count * 8}
	for code, rows in glyphs {
		for y, row in rows {
			font[(int(code) - font_first) * 8 + y] = u8(row) << 2
		}
	}
	return font
}

// glyph returns the seven rows of a character, five bits each with the left
// pixel in bit 4; a character the font lacks is blank.
pub fn glyph(c u8) []int {
	return glyphs[rune(c)] or { []int{len: 7} }
}
